import { useState } from 'react';
import { Link, useSearchParams } from 'react-router';
import { AlertOctagon, Bug, CheckCircle2, Download, FileBarChart, FileSpreadsheet, FileStack, FileText, Layers, Shuffle, XCircle } from 'lucide-react';
import { SeverityBadge, severityLabel } from '../components/badges';
import { BarList, RingGauge, SEVERITY_COLORS } from '../components/charts';
import { EmptyState, Modal, Notice, useToast } from '../components/feedback';
import { Checkbox, Select } from '../components/forms';
import { Button, ButtonLink, Card, CardHeader, DemoTag, PageHeader, StatCard, buttonCls } from '../components/ui';
import { ServerRunBadge } from '../components/RunPanel';
import { MODULES } from '../lib/catalog';
import { formatDate, num } from '../lib/format';
import { projectStats, useData } from '../lib/store';
import { SEVERITIES } from '../lib/types';

type Format = 'PDF' | 'XLSX';

function ExportModal({ format, onClose, scope }: { format?: Format; onClose: () => void; scope: string }) {
  const toast = useToast();
  const [opts, setOpts] = useState({ summary: true, issues: true, screenshots: true, steps: true, passed: false });
  const set = (k: keyof typeof opts) => (v: boolean) => setOpts((o) => ({ ...o, [k]: v }));
  return (
    <Modal
      open={!!format}
      onClose={onClose}
      title={format === 'PDF' ? 'Export PDF report' : 'Export Excel workbook'}
      description={`Scope: ${scope}`}
      footer={
        <>
          <Button onClick={onClose}>Cancel</Button>
          <Button
            variant="primary"
            icon={format === 'PDF' ? FileText : FileSpreadsheet}
            onClick={() => {
              toast({ kind: 'info', title: 'Report generation needs the backend', body: `${format} files are rendered server-side. No file was created in this preview.` });
              onClose();
            }}
          >
            Generate {format}
          </Button>
        </>
      }
    >
      <p className="mb-3 text-sm font-medium text-slate-700">Include</p>
      <div className="space-y-3">
        <Checkbox checked={opts.summary} onChange={set('summary')} label="Executive summary" description="Pass rate, totals and severity breakdown" />
        <Checkbox checked={opts.issues} onChange={set('issues')} label="Issue list" description={format === 'XLSX' ? 'One row per issue on its own sheet' : 'Every issue with expected and actual results'} />
        <Checkbox checked={opts.steps} onChange={set('steps')} label="Steps to reproduce" />
        <Checkbox checked={opts.screenshots} onChange={set('screenshots')} label={format === 'XLSX' ? 'Screenshot links' : 'Embedded screenshots'} />
        <Checkbox checked={opts.passed} onChange={set('passed')} label="Passed tests" description="Adds every passed check (large)" />
      </div>
      <Notice kind="info" className="mt-5 text-xs">Report files are generated by the backend, which isn't connected yet. This dialog shows the export options that will be available.</Notice>
    </Modal>
  );
}

export function Reports() {
  const data = useData();
  const [params, setParams] = useSearchParams();
  const [exportFmt, setExportFmt] = useState<Format>();
  const projectId = params.get('project') ?? '';
  const project = data.project(projectId);

  const tested = data.projects.filter((p) => data.runs.some((r) => r.projectId === p.id));
  const generated = data.reports.filter((r) => !project || r.projectId === project.id);
  // Scope: latest run of the selected project, or the latest run of every project.
  const runs = project ? projectStats(project, data).runs.slice(0, 1) : tested.map((p) => projectStats(p, data).latest!).filter(Boolean);
  const runIds = new Set(runs.map((r) => r.id));
  const issues = data.issues.filter((i) => runIds.has(i.runId));
  const confirmed = issues.filter((i) => i.classification === 'CONFIRMED');
  const passed = runs.reduce((a, r) => a + r.testsPassed, 0);
  const failed = runs.reduce((a, r) => a + r.testsFailed, 0);
  const flaky = runs.reduce((a, r) => a + r.testsFlaky, 0);
  const pages = runs.reduce((a, r) => a + r.pagesDiscovered, 0);
  const isDemo = runs.some((r) => r.demo);
  const scope = project ? `${project.name} — latest run` : `All projects — latest run of each (${runs.length})`;

  return (
    <>
      <PageHeader
        title="Reports"
        description="Testing summary, pass/fail counts and issue breakdown — ready to export for your team."
        actions={
          <>
            <Select aria-label="Project" value={projectId} onChange={(e) => setParams(e.target.value ? { project: e.target.value } : {}, { replace: true })} className="w-60">
              <option value="">All projects</option>
              {data.projects.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}
            </Select>
            <Button icon={FileText} onClick={() => setExportFmt('PDF')} disabled={runs.length === 0}>Export PDF</Button>
            <Button icon={FileSpreadsheet} variant="primary" onClick={() => setExportFmt('XLSX')} disabled={runs.length === 0}>Export Excel</Button>
          </>
        }
      />

      {runs.length === 0 ? (
        <Card>
          <EmptyState icon={FileBarChart} title={project ? `${project.name} hasn't been tested yet` : 'No test results to report'} action={<ButtonLink to="/configure">Configure a test</ButtonLink>}>
            Reports are built from completed test runs. Once the test engine is connected, summaries and exports appear here. Switch on <strong>Demo data</strong> to preview a report.
          </EmptyState>
        </Card>
      ) : (
        <>
          <Card className="mb-6">
            <div className="flex flex-col gap-6 p-6 md:flex-row md:items-center">
              <RingGauge value={passed / Math.max(1, passed + failed)} label="pass rate" size={136} />
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <h2 className="font-display text-lg font-bold tracking-tight text-slate-900">Testing summary</h2>
                  {data.demo && runs.some((r) => r.demo) && <DemoTag />}
                </div>
                <p className="mt-0.5 text-sm text-slate-500">{scope}</p>
                <p className="mt-3 max-w-2xl text-sm leading-relaxed text-slate-700">
                  {num(passed + failed)} checks ran across {num(pages)} pages. <strong>{num(confirmed.length)}</strong> confirmed issue{confirmed.length === 1 ? '' : 's'} with evidence
                  {confirmed.some((i) => i.severity === 'CRITICAL') && <>, including <strong className="text-rose-700">{confirmed.filter((i) => i.severity === 'CRITICAL').length} critical</strong></>}.
                  {flaky > 0 && <> {flaky} flaky result{flaky === 1 ? ' was' : 's were'} excluded from the bug count.</>}
                </p>
                <p className="mt-2 text-xs text-slate-500">Run{runs.length > 1 ? 's' : ''} finished {runs.map((r) => formatDate(r.finishedAt ?? r.startedAt)).slice(0, 3).join(', ')}{runs.length > 3 ? '…' : ''}</p>
              </div>
            </div>
          </Card>

          <div className="stagger grid grid-cols-2 gap-4 lg:grid-cols-5">
            <StatCard demo={isDemo} label="Tests passed" value={num(passed)} icon={CheckCircle2} iconCls="bg-emerald-50 text-emerald-600" />
            <StatCard demo={isDemo} label="Tests failed" value={num(failed)} icon={XCircle} iconCls="bg-rose-50 text-rose-600" />
            <StatCard demo={isDemo} label="Flaky" value={num(flaky)} icon={Shuffle} iconCls="bg-amber-50 text-amber-600" hint="Not counted as bugs" />
            <StatCard demo={isDemo} label="Pages tested" value={num(pages)} icon={FileStack} iconCls="bg-violet-50 text-violet-600" />
            <StatCard demo={isDemo} label="Confirmed issues" value={num(confirmed.length)} icon={Bug} iconCls="bg-orange-50 text-orange-600" to={project ? `/issues?project=${project.id}` : '/issues'} hint={`${issues.length - confirmed.length} unconfirmed`} />
          </div>

          <div className="mt-6 grid grid-cols-1 gap-6 lg:grid-cols-2">
            <Card>
              <CardHeader title="Issues by severity" description="Confirmed issues" icon={AlertOctagon} />
              <div className="p-5">
                <BarList
                  emptyLabel="No confirmed issues"
                  rows={SEVERITIES.map((s) => ({ key: s, label: severityLabel(s), value: confirmed.filter((i) => i.severity === s).length, color: SEVERITY_COLORS[s], to: `/issues?severity=${s}${project ? `&project=${project.id}` : ''}` }))}
                />
              </div>
            </Card>
            <Card>
              <CardHeader title="Issues by category" description="Confirmed issues per testing module" icon={Layers} />
              <div className="p-5">
                <BarList
                  emptyLabel="No confirmed issues"
                  rows={MODULES.map((m) => ({ key: m.id, label: m.name, icon: <m.icon className="size-4 text-slate-400" />, value: confirmed.filter((i) => i.module === m.id).length, color: 'var(--color-viz-blue)', to: `/issues?category=${m.id}${project ? `&project=${project.id}` : ''}` }))
                    .filter((r) => r.value > 0)}
                />
              </div>
            </Card>
          </div>

          <Card className="mt-6">
            <CardHeader title="Results by project" icon={FileBarChart} />
            <div className="relative overflow-x-auto">
              <table className="app-table min-w-full text-sm">
                <thead><tr className="border-b border-slate-200/80 text-left text-[11px] font-semibold uppercase tracking-[0.08em] text-slate-500"><th className="px-5 py-3">Project</th><th className="px-4 py-3 text-right">Pages</th><th className="px-4 py-3 text-right">Passed</th><th className="px-4 py-3 text-right">Failed</th><th className="px-4 py-3 text-right">Pass rate</th><th className="px-4 py-3">Highest severity</th><th className="px-5 py-3 text-right">Issues</th></tr></thead>
                <tbody className="divide-y divide-slate-100">
                  {runs.map((r) => {
                    const p = data.project(r.projectId)!;
                    const pi = confirmed.filter((i) => i.runId === r.id);
                    const top = SEVERITIES.find((s) => pi.some((i) => i.severity === s));
                    return (
                      <tr key={r.id}>
                        <td className="px-5 py-3"><Link to={`/projects/${p.id}`} className="flex items-center gap-2 font-medium text-slate-900 hover:text-brand-600">{p.name}{p.demo && <DemoTag />}</Link><p className="text-xs text-slate-500">{formatDate(r.finishedAt ?? r.startedAt)}</p></td>
                        <td className="px-4 py-3 text-right tabular-nums">{r.pagesDiscovered}</td>
                        <td className="px-4 py-3 text-right tabular-nums">{r.testsPassed}</td>
                        <td className="px-4 py-3 text-right tabular-nums">{r.testsFailed}</td>
                        <td className="px-4 py-3 text-right tabular-nums">{((r.testsPassed / Math.max(1, r.testsPassed + r.testsFailed)) * 100).toFixed(1)}%</td>
                        <td className="px-4 py-3">{top ? <SeverityBadge s={top} /> : <span className="text-slate-400">—</span>}</td>
                        <td className="px-5 py-3 text-right tabular-nums"><Link to={`/issues?project=${p.id}`} className="text-brand-600 hover:underline">{pi.length}</Link></td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </Card>
        </>
      )}

      <Card className="mt-6">
        <CardHeader title="Generated reports" description="PDF reports created by the testing engine after each completed run" icon={FileText} />
        {generated.length === 0 ? (
          <EmptyState compact icon={FileText} title="No reports generated yet">A PDF report is generated automatically when a test run completes.</EmptyState>
        ) : (
          <div className="relative overflow-x-auto">
            <table className="app-table min-w-full text-sm">
              <thead>
                <tr className="border-b border-slate-200/80 text-left text-[11px] font-semibold uppercase tracking-[0.08em] text-slate-500">
                  <th className="px-5 py-2.5">Project</th><th className="px-4 py-2.5">Test run</th><th className="px-4 py-2.5">Status</th><th className="px-4 py-2.5 text-right">Issues</th><th className="px-4 py-2.5 text-right">Size</th><th className="px-5 py-2.5 text-right"><span className="sr-only">Actions</span></th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {generated.map((r) => (
                  <tr key={r.id}>
                    <td className="px-5 py-3"><Link to={`/projects/${r.projectId}?run=${r.run.id}`} className="font-medium text-slate-900 hover:text-brand-600">{data.project(r.projectId)?.name ?? r.run.project.name}</Link><p className="truncate text-xs text-slate-500">{r.run.project.baseUrl}</p></td>
                    <td className="whitespace-nowrap px-4 py-3 text-slate-700">{formatDate(r.run.startedAt ?? r.run.queuedAt)}<p className="font-mono text-[11px] text-slate-400">{r.run.id.slice(0, 8)}</p></td>
                    <td className="px-4 py-3"><ServerRunBadge s={r.run.status} /></td>
                    <td className="px-4 py-3 text-right tabular-nums">{r.run.confirmedIssues}</td>
                    <td className="px-4 py-3 text-right tabular-nums text-slate-500">{(r.sizeBytes / 1024 / 1024).toFixed(1)} MB</td>
                    <td className="px-5 py-3">
                      <div className="flex justify-end gap-1">
                        <a href={r.url} target="_blank" rel="noreferrer" className={buttonCls('secondary', 'sm')}><FileText className="size-3.5" /> Open PDF</a>
                        <a href={r.url} download className={buttonCls('ghost', 'sm')}><Download className="size-3.5" /> Download</a>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      <ExportModal format={exportFmt} onClose={() => setExportFmt(undefined)} scope={scope} />
    </>
  );
}
